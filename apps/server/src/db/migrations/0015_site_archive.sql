-- Archived sites — D138: a finished site is put away, not deleted.
--
-- A studio finishes a client's site and wants it out of the list without
-- losing what the client said. `archived_at` set means archived: the site
-- and every thread on it stay readable, the widget on the client's page
-- shows it read-only, nothing new is written to it, and it is not counted
-- against the plan's site cap. Restoring clears the column, and is refused
-- when the studio's plan has no room for another active site.
--
-- The same column is how a studio over its cap after a downgrade gets back
-- under it: sites beyond the cap (newest first) are read-only until one is
-- archived or the plan grows. That lock is computed (holds.ts), not stored,
-- so a plan change applies at once and nothing has to be unlocked.
ALTER TABLE projects ADD COLUMN archived_at timestamptz;
